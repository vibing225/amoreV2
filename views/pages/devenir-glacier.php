    <script>
        lucide.createIcons();
        
        const mobileMenuBtn = document.getElementById('mobile-menu-btn');
        const mobileMenu = document.getElementById('mobile-menu');

        mobileMenuBtn.addEventListener('click', () => {
            mobileMenu.classList.toggle('hidden');
        });

        const mobileMenuLinks = mobileMenu.querySelectorAll('a');
        mobileMenuLinks.forEach(link => {
            link.addEventListener('click', () => {
                mobileMenu.classList.add('hidden');
            });
        });

        // Form adaptivity
        const franchiseFields = document.getElementById('franchise-fields');
        const partenaireFields = document.getElementById('partenaire-fields');
        const matieresFields = document.getElementById('matieres-fields');

        function selectOption(type) {
            // Set the radio button
            const radio = document.getElementById('opt-' + type);
            if (radio) {
                radio.checked = true;
                updateFormFields(type);
            }
        }

        function updateFormFields(selectedType) {
            console.log('Updating form for type:', selectedType);
            
            // Hide all conditional fields first
            franchiseFields.style.display = 'none';
            partenaireFields.style.display = 'none';
            matieresFields.style.display = 'none';

            // Remove required from all conditional fields
            document.querySelectorAll('.franchise-required, .partenaire-required, .matieres-required').forEach(field => {
                field.removeAttribute('required');
            });

            // Show selected fields and add required
            if (selectedType === 'franchise') {
                franchiseFields.style.display = 'block';
                document.querySelectorAll('.franchise-required').forEach(field => {
                    field.setAttribute('required', 'required');
                });
            } else if (selectedType === 'partenaire') {
                partenaireFields.style.display = 'block';
                document.querySelectorAll('.partenaire-required').forEach(field => {
                    field.setAttribute('required', 'required');
                });
            } else if (selectedType === 'matieres') {
                matieresFields.style.display = 'block';
                document.querySelectorAll('.matieres-required').forEach(field => {
                    field.setAttribute('required', 'required');
                });
            }
        }

        // Handle direct radio button changes (backup)
        document.querySelectorAll('input[name="candidature_type"]').forEach(radio => {
            radio.addEventListener('change', (e) => {
                if (e.target.checked) {
                    updateFormFields(e.target.value);
                }
            });
        });

        // Check URL parameter on page load
        window.addEventListener('load', () => {
            // First check for hash with query params (e.g., #form-candidature?type=franchise)
            const fullHash = window.location.hash;
            let typeParam = null;
            
            if (fullHash.includes('?')) {
                const hashParts = fullHash.split('?');
                const hashParams = new URLSearchParams(hashParts[1]);
                typeParam = hashParams.get('type');
            }
            
            // Also check regular query params
            if (!typeParam) {
                const urlParams = new URLSearchParams(window.location.search);
                typeParam = urlParams.get('type');
            }
            
            console.log('Type param found:', typeParam);
            
            // Pre-select option based on URL parameter
            if (typeParam && ['franchise', 'partenaire', 'matieres'].includes(typeParam)) {
                selectOption(typeParam);
                
                // Scroll to form after a short delay
                setTimeout(() => {
                    const formSection = document.getElementById('form-candidature');
                    if (formSection) {
                        formSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
                    }
                }, 300);
            }
        });

        // Handle hash links with parameters
        document.querySelectorAll('a[href*="#form-candidature"]').forEach(link => {
            link.addEventListener('click', (e) => {
                const href = link.getAttribute('href');
                const typeMatch = href.match(/[?&]type=(\w+)/);
                
                if (typeMatch) {
                    e.preventDefault();
                    const type = typeMatch[1];
                    selectOption(type);
                    
                    // Scroll to form
                    const formSection = document.getElementById('form-candidature');
                    if (formSection) {
                        formSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
                    }
                }
            });
        });
    </script>
